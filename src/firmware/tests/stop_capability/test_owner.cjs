'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {spawn}=require('node:child_process');const readline=require('node:readline');
const {PhoneControl}=require('../../components/robot_phone/web/app.js');
const root=path.resolve(__dirname,'../../../..'),[exe,out]=process.argv.slice(2);fs.mkdirSync(out,{recursive:true});
const trace=JSON.parse(fs.readFileSync(path.join(root,'.dev/phone-transfer-evidence/selected-handoff-stop/handoff-stop.json'),'utf8'));
let checks=0;function ok(v,m){++checks;assert.ok(v,m);}
async function scenario(mode){
 const child=spawn(exe,['true']),pending=[],events=[],commands=[];let error=null,clock=0,heldAck,combinedResult,drop='';
 const exited=new Promise(resolve=>child.once('exit',code=>{error=Error('actor exit '+code);pending.splice(0).forEach(p=>p.reject(error));resolve(code);}));
 child.stderr.on('data',b=>events.push({stderr:b.toString()}));
 readline.createInterface({input:child.stdout}).on('line',line=>{const p=pending.shift();if(p){try{p.resolve(JSON.parse(line));}catch(e){p.reject(e);}}});
 const request=text=>new Promise((resolve,reject)=>{if(error)return reject(error);pending.push({resolve,reject});child.stdin.write(text+'\n');});
 const req=async text=>{const r=await request(text);events.push({text,result:r});if(text.startsWith('W '))clock=Number(r.at);return r;};
 let expected=null;
 const c=new PhoneControl(async(url,options)=>{
  if(url==='/api/session')return {wire_error:0,credential:'b'.repeat(32)}; // seeded actualOwner session, same as032 fixture
  if(url==='/api/status')return req('P');
  if(expected!==null)assert.equal(options.body,expected,'original public Boot command');
  const fields=options.body.split('|'),row={op:fields[5],body:options.body,origin_auth:options.headers['X-Session-Credential']==='b'.repeat(32)};commands.push(row);
  if(row.op==='stop'&&drop==='before'){drop='';throw Error('lost before delivery');}
  const r=await req('A '+options.headers['X-Session-Credential']+' '+options.body);row.result=r;
  if(row.op==='handoff-acquire'){combinedResult=r;await new Promise(resolve=>{heldAck=resolve;});}
  if(row.op==='stop'&&drop==='after'){drop='';throw Error('ACK lost after actual acceptance');}
  return r;
 },()=>clock);
 let ack,report={mode,result:'RUNNING',scope:'actual production JS -> authenticated actual C++ Owner/Boot/Run/Gate/FakeCAN; recorded Boot setup schedule; NOT new DOM'};
 try{
  await c.pair('a'.repeat(32));
  for(const ev of trace.actor){if(ev.kind!=='actor')continue;await req('W '+ev.clock);
   if(ev.text.startsWith('C ')){
    const f=ev.text.slice(2).split('|');expected=f.join('|');
    if(f[5]==='handoff-acquire'){
     ack=c.transferAndAcquire();for(let n=0;n<1000&&!heldAck;++n)await new Promise(r=>setTimeout(r,1));ok(!!heldAck,'combined accepted and ACK held');expected=null;break;
    }
    await c.command(f[5],{direction:Number(f[9]),unloaded:f[10]==='1'});expected=null;
   }else{const r=await req(ev.text);if(ev.text==='P')c.update(r);}
  }
  ok(combinedResult.wire_error===0,'actual reservation accepted');const id=c.stopBinding.id;ok(id==='29','original wire identity generated by JS');
  await req('W '+(mode==='granted'?'6900':'6419'));
  c.visible(false);c.visible(true);
  if(mode==='disconnect'||mode==='lost-before'||mode==='lost-after')c.disconnect();
  if(mode==='lost-before'||mode==='lost-after'){
   drop=mode==='lost-before'?'before':'after';await assert.rejects(c.command('stop'));ok(c.stopBinding.id===id,'failed transport retains identity');
   if(mode==='lost-after')await assert.rejects(c.command('stop'));else await c.command('stop');
  }else if(mode.startsWith('wrong-')){
   const f=['v1','11','1','30','30','stop','0',id,'1','0','0'];let credential='b'.repeat(32);
   if(mode==='wrong-nonce')f[7]='30';if(mode==='wrong-axis')f[8]='2';if(mode==='wrong-boot')f[1]='12';if(mode==='wrong-generation')f[2]='4';if(mode==='wrong-credential')credential='c'.repeat(32);
   const denial=await req('A '+credential+' '+f.join('|'));ok(denial.wire_error!==0,'identity mismatch actual Owner denial');
   ok((await req('P')).stop_at==='0','denied Stop did not stop');await c.command('stop');
  }else await c.command('stop');
  const immediate=await req('P');ok(BigInt(immediate.stop_at)>0n,'actual Stop reached');ok(c.busy,'normal held ACK remains busy');
  const stopCommands=commands.filter(x=>x.op==='stop');ok(stopCommands.every(x=>x.body.split('|')[7]===id&&x.origin_auth),'actual producer retained key+origin auth');
  heldAck();await ack;ok(c.authority===''&&!c.handoffIntent,'late ACK cannot grant locally');
  await req('W '+(mode==='granted'?'7200':'6900'));const metrics=await req('M');ok(metrics.transfer_attempts===(mode==='granted'?1:0),'actual attempts after Stop');ok(metrics.moves===0,'actual no FD');
  await c.poll();ok(!!c.stopBinding,'phase3 cannot discard recovery auth');
  await req('W 11000');await c.poll();ok(c.snapshot.phase===4&&c.snapshot.stop_verified,'actual final stop verification read');ok(c.stopBinding===null,'actual terminal retired identity');
  report={...report,result:'PASS',immediate,metrics,final:c.snapshot,checks};
 }catch(e){report={...report,result:'FAIL',error:String(e)};throw e;}
 finally{Object.assign(report,{commands,events});fs.writeFileSync(path.join(out,mode+'.json'),JSON.stringify(report,null,2));child.stdin.end();await exited;}
}
(async()=>{for(const mode of ['pending','granted','disconnect','lost-before','lost-after','wrong-nonce','wrong-axis','wrong-boot','wrong-generation','wrong-credential']){await scenario(mode);console.log('SC OWNER PASS '+mode);}console.log('SC OWNER PASS checks='+checks+'; no injected seq/lease/Acquire/Ready; recorded public Boot schedule; hardware NOT_RUN');})().catch(e=>{console.error(e);process.exitCode=1;});
